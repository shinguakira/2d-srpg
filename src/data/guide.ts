export const GUIDE_COUNT = GUIDE.length;

/** その行の説明。指のときは頭の何行かが入れ替わる */
export function guideText(i: number, touch: boolean): string {
  if (touch && i < TOUCH_GUIDE.length) return TOUCH_GUIDE[i];
  return GUIDE[i][1];
}
