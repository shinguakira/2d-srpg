import type { Rank, Weapon, WeaponType } from '../types';

const RANK_ORDER: Rank[] = ['E', 'D', 'C', 'B', 'A', 'S'];

/** 武器熟練度 → ランク（GBA 系 FE の値） */
export const WEXP_THRESHOLD: Record<Rank, number> = { E: 0, D: 31, C: 71, B: 121, A: 181, S: 251 };

export function rankFromWexp(wexp: number): Rank {
  let r: Rank = 'E';
  for (const k of RANK_ORDER) if (wexp >= WEXP_THRESHOLD[k]) r = k;
  return r;
}

export function rankAtLeast(a: Rank, b: Rank): boolean {
  return RANK_ORDER.indexOf(a) >= RANK_ORDER.indexOf(b);
}

