export function cloneWeapon(id: string): Weapon {
  const src = WEAPONS[id];
  if (!src) throw new Error(`unknown weapon: ${id}`);
  return { ...src, effective: src.effective ? [...src.effective] : undefined };
}

/**
 * 三すくみ。
 * 武器: 剣 > 斧 > 槍 > 剣
 * 魔法: 理 > 光 > 闇 > 理
 */
export function triangle(a: WeaponType, d: WeaponType): -1 | 0 | 1 {
  const win: Partial<Record<WeaponType, WeaponType>> = {
    sword: 'axe',
    axe: 'lance',
    lance: 'sword',
    anima: 'light',
    light: 'dark',
    dark: 'anima',
  };
  if (win[a] === d) return 1;
  if (win[d] === a) return -1;
  return 0;
}

